import { defineType, defineField, defineArrayMember } from "sanity";
import { EarthGlobeIcon } from "@sanity/icons/EarthGlobe";

export const tour = defineType({
  name: "tour",
  title: "Tour",
  type: "document",
  icon: EarthGlobeIcon,
  groups: [
    { name: "content", title: "Content", default: true },
    { name: "logistics", title: "Logistics" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      group: "content",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "slug",
      title: "Slug",
      type: "slug",
      group: "content",
      options: { source: "title", maxLength: 96 },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "shortDescription",
      title: "Short Description",
      type: "text",
      group: "content",
      rows: 2,
      validation: (rule) => rule.max(200).warning("Keep it under 200 characters for card layouts"),
    }),
    defineField({
      name: "description",
      title: "Description",
      type: "array",
      group: "content",
      of: [defineArrayMember({ type: "block" })],
    }),
    defineField({
      name: "heroImage",
      title: "Hero Image",
      type: "image",
      group: "content",
      options: { hotspot: true },
      fields: [
        defineField({ name: "alt", title: "Alt Text", type: "string", validation: (rule) => rule.required() }),
      ],
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "gallery",
      title: "Gallery",
      type: "array",
      group: "content",
      of: [
        defineArrayMember({
          type: "image",
          options: { hotspot: true },
          fields: [defineField({ name: "alt", title: "Alt Text", type: "string" })],
        }),
      ],
    }),
    defineField({
      name: "duration",
      title: "Duration",
      type: "string",
      group: "logistics",
      description: "e.g. '3 hours', '2 days'",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "difficulty",
      title: "Difficulty",
      type: "string",
      group: "logistics",
      options: { list: ["Easy", "Moderate", "Challenging"], layout: "radio" },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "price",
      title: "Price",
      type: "number",
      group: "logistics",
      validation: (rule) => rule.required().positive(),
    }),
    defineField({
      name: "originalPrice",
      title: "Original Price (for discounts)",
      type: "number",
      group: "logistics",
      validation: (rule) => rule.positive(),
    }),
    defineField({
      name: "currency",
      title: "Currency",
      type: "string",
      group: "logistics",
      initialValue: "EUR",
      options: { list: ["EUR", "USD", "GBP"] },
    }),
    defineField({
      name: "badges",
      title: "Badges",
      type: "array",
      group: "logistics",
      of: [defineArrayMember({ type: "string" })],
      options: { list: ["Bestseller", "Launch Offer", "New"] },
    }),
    defineField({
      name: "rating",
      title: "Rating",
      type: "number",
      group: "logistics",
      description: "Aggregate rating from the review platform, entered manually for now.",
      validation: (rule) => rule.required().min(0).max(5),
    }),
    defineField({
      name: "reviewCount",
      title: "Review Count",
      type: "number",
      group: "logistics",
      validation: (rule) => rule.required().min(0),
    }),
    defineField({
      name: "categories",
      title: "Categories",
      type: "array",
      group: "content",
      of: [defineArrayMember({ type: "reference", to: [{ type: "category" }] })],
      validation: (rule) => rule.min(1).error("Assign at least one category"),
    }),
    defineField({
      name: "meetingPoint",
      title: "Meeting Point",
      type: "string",
      group: "logistics",
    }),
    defineField({
      name: "itinerary",
      title: "Itinerary",
      type: "array",
      group: "content",
      of: [
        defineArrayMember({
          type: "object",
          name: "itineraryStep",
          fields: [
            defineField({ name: "title", title: "Title", type: "string" }),
            defineField({ name: "description", title: "Description", type: "text", rows: 2 }),
            defineField({ name: "duration", title: "Duration", type: "string" }),
          ],
          preview: { select: { title: "title", subtitle: "duration" } },
        }),
      ],
    }),
    defineField({
      name: "included",
      title: "Included",
      type: "array",
      group: "logistics",
      of: [defineArrayMember({ type: "string" })],
    }),
    defineField({
      name: "excluded",
      title: "Not Included",
      type: "array",
      group: "logistics",
      of: [defineArrayMember({ type: "string" })],
    }),
    defineField({
      name: "whatToBring",
      title: "What to Bring",
      type: "array",
      group: "logistics",
      of: [defineArrayMember({ type: "string" })],
    }),
    defineField({
      name: "faqs",
      title: "FAQs",
      type: "array",
      group: "content",
      of: [
        defineArrayMember({
          type: "object",
          name: "faqItem",
          fields: [
            defineField({ name: "question", title: "Question", type: "string" }),
            defineField({ name: "answer", title: "Answer", type: "text", rows: 3 }),
          ],
          preview: { select: { title: "question" } },
        }),
      ],
    }),
    defineField({
      name: "seo",
      title: "SEO",
      type: "object",
      group: "seo",
      fields: [
        defineField({ name: "metaTitle", title: "Meta Title", type: "string" }),
        defineField({ name: "metaDescription", title: "Meta Description", type: "text", rows: 2 }),
      ],
    }),
  ],
  preview: {
    select: {
      title: "title",
      subtitle: "duration",
      media: "heroImage",
    },
  },
});
